// Writes the Sasha Slides brand kit into this folder, from the same geometry the website's animated
// logo uses (renderer/html2slides/addon-server/site/logo-display.ts): 34 sunflower cells shaded
// along the 8 spirals, on a graphite rounded square.
//
//   npx tsx mcp/sasha-slides/docs/brand/export-brand.ts
//
// PNGs are rendered by headless Chrome (transparent background), so gradients and the wordmark's
// Hanken Grotesk come out exactly as a browser shows them. favicon.ico is packed by ImageMagick.

import { execFileSync } from "node:child_process";
import { mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { PATTERNS, SEED_COUNT, TONES, cellPath, seedCells } from "../../../../renderer/html2slides/addon-server/site/logo-display.ts";

const HERE = dirname(fileURLToPath(import.meta.url));
const SQUIRCLE = "M100 0 C178 0 200 22 200 100 C200 178 178 200 100 200 C22 200 0 178 0 100 C0 22 22 0 100 0 Z";
const WORDMARK_FONT = "https://fonts.googleapis.com/css2?family=Hanken+Grotesk:wght@600&display=swap";

function cells(): string {
  return seedCells({ count: SEED_COUNT, radius: 72 })
    .map((cell) => `<path d="${cellPath(cell.polygon, 4, 5)}" fill="${TONES[PATTERNS[0].tone(cell)]}"/>`)
    .join("");
}

/** The app icon: cells on the graphite rounded square. `id` keeps gradient ids unique when inlined twice. */
export function iconSvg(id = "sasha"): string {
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 200 200">` +
    `<defs><linearGradient id="${id}-bg" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#2C2C2E"/><stop offset="1" stop-color="#0A0A0B"/></linearGradient></defs>` +
    `<path d="${SQUIRCLE}" fill="url(#${id}-bg)"/>${cells()}</svg>`
  );
}

/** The mark alone, no background, for placing on graphite or photography. */
function markSvg(): string {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="28 28 144 144">${cells()}</svg>`;
}

/** Icon plus "Sasha Slides", set in Hanken Grotesk 600. `ink` is the text colour. */
function wordmarkSvg(ink: string): string {
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 860 200">` +
    `<style>@import url('${WORDMARK_FONT}');</style>` +
    `<g>${iconSvg(`wm${ink.slice(1)}`).replace(/^<svg[^>]*>/, "").replace(/<\/svg>$/, "")}</g>` +
    `<text x="236" y="128" font-family="'Hanken Grotesk', 'Helvetica Neue', Helvetica, Arial, sans-serif" font-weight="600" font-size="96" letter-spacing="-2.4" fill="${ink}">Sasha Slides</text></svg>`
  );
}

function renderPng(options: Readonly<{ svg: string; width: number; height: number; out: string; scratch: string }>): void {
  const page = join(options.scratch, "render.html");
  writeFileSync(
    page,
    `<!doctype html><html><head><link rel="stylesheet" href="${WORDMARK_FONT}"><style>html,body{margin:0;background:transparent}svg{display:block;width:${options.width}px;height:${options.height}px}</style></head><body>${options.svg}</body></html>`,
  );
  execFileSync(
    "google-chrome",
    [
      "--headless=new",
      "--no-sandbox",
      "--disable-gpu",
      "--hide-scrollbars",
      "--default-background-color=00000000",
      `--window-size=${options.width},${options.height}`,
      "--virtual-time-budget=2000",
      `--screenshot=${options.out}`,
      `file://${page}`,
    ],
    { stdio: "ignore", timeout: 20_000 },
  );
}

function main(): void {
  const scratch = mkdtempSync(join(tmpdir(), "sasha-brand-"));
  try {
    const files: Record<string, string> = {
      "sasha-slides-icon.svg": iconSvg(),
      "sasha-slides-mark.svg": markSvg(),
      "sasha-slides-wordmark-on-light.svg": wordmarkSvg("#1D1D1F"),
      "sasha-slides-wordmark-on-dark.svg": wordmarkSvg("#F5F5F7"),
    };
    for (const [name, svg] of Object.entries(files)) writeFileSync(join(HERE, name), `${svg}\n`);
    // The account portal inlines the icon (its CSP allows no images), so it gets a TypeScript copy.
    writeFileSync(
      join(HERE, "../../http/sasha-icon.generated.ts"),
      `// Generated by docs/brand/export-brand.ts. Do not edit.\nexport const SASHA_ICON_SVG = ${JSON.stringify(iconSvg("sasha-icon").replace("<svg ", '<svg aria-hidden="true" focusable="false" '))};\n`,
    );

    for (const size of [16, 32, 48, 64, 120, 180, 512, 1024]) {
      renderPng({ svg: iconSvg(), width: size, height: size, out: join(HERE, `sasha-slides-icon-${size}.png`), scratch });
    }
    renderPng({ svg: files["sasha-slides-wordmark-on-light.svg"], width: 1720, height: 400, out: join(HERE, "sasha-slides-wordmark-on-light.png"), scratch });
    renderPng({ svg: files["sasha-slides-wordmark-on-dark.svg"], width: 1720, height: 400, out: join(HERE, "sasha-slides-wordmark-on-dark.png"), scratch });
    // The legacy 120px name the Google consent screen upload was pointed at.
    execFileSync("cp", [join(HERE, "sasha-slides-icon-120.png"), join(HERE, "sasha-slides-logo-120.png")]);
    execFileSync("convert", [16, 32, 48].map((s) => join(HERE, `sasha-slides-icon-${s}.png`)).concat(join(HERE, "favicon.ico")), { timeout: 20_000 });
  } finally {
    rmSync(scratch, { recursive: true, force: true });
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
